def randomize_music(world: InStarsAndTimeWorld) -> None:
    # Took this from v6's APWorld
    bgm_shuffled = BGM.copy()
    if world.options.music_rando:
        world.multiworld.random.shuffle(bgm_shuffled)
    world.bgm_map = dict(zip(BGM, bgm_shuffled))